def results_table() -> list[str]:
    n = {split: metrics("agent_v2_haiku", split)["n_cases"] for split in SPLITS}
    lines = [
        "## Results",
        "",
        f"Generated from `results/` by {link('eval/readme.py')}; rates are k/n (value; 95 % Wilson interval, "
        f"{link('eval/metrics.py')}). Splits: dev {n['dev']} cases (prompts iterated here), test {n['test']} "
        f"(frozen, run once per system), robust {n['robust']} (new templates written after the prompts were frozen) "
        f"({link('data/test.sha256')}, {link('data/robust.sha256')}). Every system, agent v1 and the probes included: "
        f"{link('results/comparison.md')}.",
        "",
        "| system | split | dangerous approvals | unjustified PEND | decision accuracy | criterion accuracy | "
        "cost per case (USD) | source |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for system, label in SYSTEMS:
        for split in SPLITS:
            m = metrics(system, split)
            per_case = m["usage"]["cost_usd_per_case"]["mean"] or 0.0
            cells = [
                label,
                split,
                rate(m["dangerous_approval_rate"]),
                rate(m["unjustified_pend_rate"]),
                rate(m["decision_accuracy"]),
                rate(m["criterion_accuracy"]),
                f"{per_case:.5f}",
                link(result_path(system, split), "json"),
            ]
            lines.append("| " + " | ".join(cells) + " |")
    return [*lines, ""]


def show_and_not() -> list[str]:
    dangerous = {
        label: [metrics(s, split)["dangerous_approval_rate"] for split in SPLITS] for s, label in LLM_SYSTEMS.items()
    }
    summary_quotes = sum(
        any(" | " in i["evidence"]["quote"] for i in json.loads(line)["invalid_evidence"])
        for line in (ROOT / "results/pipeline_dev_errors.jsonl").read_text(encoding="utf-8").splitlines()
        if line.strip()
    )
    llm_zero = all(r["k"] == 0 for rates in dangerous.values() for r in rates)
    rules = [metrics("rules_baseline", split)["dangerous_approval_rate"] for split in SPLITS]
    inj = [metrics("agent_v2_haiku", split)["injection_detection"] for split in SPLITS]
    base_dec = [metrics("agent_v2_haiku", split)["decision_accuracy"] for split in SPLITS]
    single_dec = [metrics("llm_single_haiku", split)["decision_accuracy"] for split in SPLITS]
    single_overlap = sum(overlap(a, b) for a, b in zip(base_dec, single_dec, strict=True))
    base_crit = [metrics("agent_v2_haiku", split)["criterion_accuracy"] for split in SPLITS]
    pipe_crit = [metrics("pipeline", split)["criterion_accuracy"] for split in SPLITS]
    pipe_overlap = sum(overlap(a, b) for a, b in zip(base_crit, pipe_crit, strict=True))
    mn = load("results/minimum_necessary.json")["splits"]
    sizes = ", ".join(f"{split} {metrics('agent_v2_haiku', split)['n_cases']}" for split in SPLITS)
    lines = [
        "## What the results show and do not show",
        "",
        "They show:",
        "",
        (
            f"- {'No' if llm_zero else 'Not every'} LLM-based system approved a case whose expected decision is PEND, "
            "on any split (dangerous approvals "
            + "; ".join(f"{s}: " + ", ".join(short(r) for r in rates) for s, rates in dangerous.items())
            + f"; dev, test, robust), while the rules baseline approved {', '.join(short(r) for r in rules)} of them "
            f"({link('results/comparison.md')}, {link('results/pipeline_comparison.md')})."
        ),
        f"- Agent v2 (Haiku) flagged the hidden instructions in {', '.join(short(r) for r in inj)} injection cases "
        f"on dev, test and robust ({link('results/agent_v2_haiku_dev.json')}, "
        f"{link('results/agent_v2_haiku_test.json')}, "
        f"{link('results/agent_v2_haiku_robust.json')}).",
        "- The regression gate replays the production agent on every CI run and fails on any new dangerous approval "
        f"({link('eval/gate.py')}, {link('tests/test_gate.py')}, {link('.github/workflows/ci.yml')}).",
        "",
        "They do not show:",
        "",
        "- **A measurable effect of the API pipeline** (minimum-necessary pages and redaction): criterion accuracy "
        + ", ".join(f"{short(a)} -> {short(b)}" for a, b in zip(base_crit, pipe_crit, strict=True))
        + f" on dev, test and robust, one recorded run per arm; the 95 % intervals overlap on {pipe_overlap} of 3 "
        f"splits ({link('results/pipeline_comparison.md')}, {link('docs/LIMITS.md')}).",
        "- **That the agent beats a single call by much.** Baseline 2, one Haiku call with no tools, reaches decision "
        f"accuracy {', '.join(short(r) for r in single_dec)} against {', '.join(short(r) for r in base_dec)} for "
        f"agent v2 on dev, test and robust; the intervals overlap on {single_overlap} of 3 splits "
        f"({link('results/llm_single_haiku_test.json')}, {link('results/agent_v2_haiku_test.json')}).",
        "- **That a verified citation means what the model says it means.** The verifier checks that the quote occurs "
        "on the cited page, not that it supports the claimed status "
        f"({link('src/priorauth/agent/verifier.py')}).",
        f"- **That citations never fail.** Through the pipeline, in {summary_quotes} dev cases the model quoted the "
        'page summary returned by the `list_pages` tool (two heading lines joined by " | ") as page text; the '
        f"verifier rejected it and the approvable case was pended ({link('results/pipeline_dev_errors.jsonl')}).",
        "- **An independent test.** One author wrote the record templates, the gold labels, the baseline 1 rules and "
        f"the prompts ({link('docs/LIMITS.md')}).",
        "- **That page selection generalises.** The rule was written from dev headings and sends "
        f"{100 * mn['robust']['share_of_pages_sent']:.0f} % of the robust pages, against "
        f"{100 * mn['dev']['share_of_pages_sent']:.1f} % on dev ({link('results/minimum_necessary.json')}).",
        f"- **Precise rates.** The splits are small ({sizes} cases); see the intervals above "
        f"({link('eval/metrics.py')}).",
        "- **Real-world performance.** The records are clean synthetic text, not faxes; no clinician reviewed the "
        f"labels ({link('docs/LIMITS.md')}).",
        "",
    ]
    return lines


