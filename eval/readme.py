"""Generate README.md from results/ (never edit README.md by hand).

    make readme                         # writes README.md
    python -m eval.readme --check       # exit 1 if README.md is not what this script writes

Every number in the README is read from a committed result file, and every paragraph and list item links to the file
(result, test, code or workflow) it rests on; tests/test_readme.py checks both. The demo URL comes from
docs/demo_url.txt (empty until the demo is deployed, see docs/DEPLOY.md).
"""

import argparse
import json
import sys
from pathlib import Path
from typing import Any

from priorauth.demo.examples import EXAMPLES
from priorauth.demo.server import DEFAULT_REVIEWER_PASSWORD, REVIEWER

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "README.md"
SPLITS = ("dev", "test", "robust")
REPO = "26sneakysnake/priorauth-agent"
SYSTEMS = (
    ("rules_baseline", "Baseline 1: rules, no LLM"),
    ("llm_single_haiku", "Baseline 2: one Haiku call, no tools"),
    ("agent_v2_haiku", "Agent v2 (Haiku), whole record"),
    ("agent_v2_sonnet", "Agent v2 (Sonnet), whole record"),
    ("pipeline", "Agent v2 (Haiku) through the API pipeline"),
)
LLM_SYSTEMS = {
    "llm_single_haiku": "baseline 2",
    "agent_v1_haiku": "agent v1",
    "agent_v2_haiku": "agent v2 (Haiku)",
    "agent_v2_sonnet": "agent v2 (Sonnet)",
    "pipeline": "agent v2 through the pipeline",
}


def result_path(system: str, split: str) -> str:
    return f"results/pipeline_{split}.json" if system == "pipeline" else f"results/{system}_{split}.json"


def load(path: str) -> dict[str, Any]:
    data: dict[str, Any] = json.loads((ROOT / path).read_text(encoding="utf-8"))
    return data


def metrics(system: str, split: str) -> dict[str, Any]:
    m: dict[str, Any] = load(result_path(system, split))["metrics"]
    return m


def rate(r: dict[str, Any]) -> str:
    if r["n"] == 0:
        return "n/a"
    lo, hi = r["ci95"]
    return f"{r['k']}/{r['n']} ({100 * r['value']:.1f} %; {100 * lo:.1f}-{100 * hi:.1f})"


def short(r: dict[str, Any]) -> str:
    return f"{r['k']}/{r['n']}"


def overlap(a: dict[str, Any], b: dict[str, Any]) -> bool:
    return bool(a["ci95"][0] <= b["ci95"][1] and b["ci95"][0] <= a["ci95"][1])


def link(path: str, text: str | None = None) -> str:
    return f"[{text or path}]({path})"


def demo_url() -> str:
    path = ROOT / "docs/demo_url.txt"
    return path.read_text(encoding="utf-8").strip() if path.exists() else ""


