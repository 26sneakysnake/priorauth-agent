"""Comparison table: agent v2 on whole records (P3 harness) vs agent v2 through the API pipeline (P7bis).

    uv run python -m eval.pipeline_report        # -> results/pipeline_comparison.md

Reads results/agent_v2_haiku_<split>.json and results/pipeline_<split>.json; both come from recorded runs of the same
model and prompt (claude-haiku-5-5, agent@v2). Generated, never edited by hand; tests/test_pipeline_eval.py checks
that the committed file is what this script writes.
"""

import json
from pathlib import Path
from typing import Any

from eval.run import SPLITS, load_split

RESULTS = Path("results")
OUTPUT = RESULTS / "pipeline_comparison.md"
BASELINE = "agent_v2_haiku"


def rate(r: dict[str, Any]) -> str:
    if r["n"] == 0:
        return "n/a"
    lo, hi = r["ci95"]
    return f"{r['k']}/{r['n']} = {r['value']:.4f} [{lo:.3f}, {hi:.3f}]"


def load(name: str) -> dict[str, Any]:
    data: dict[str, Any] = json.loads((RESULTS / name).read_text(encoding="utf-8"))
    return data


def render(data: Path = Path("data")) -> str:
    lines = [
        "# Agent v2 on Haiku: whole records vs the API pipeline",
        "",
        "Generated by `eval/pipeline_report.py` from `results/agent_v2_haiku_<split>.json` (P3 evaluation harness, the "
        "agent reads every page of the unredacted record) and `results/pipeline_<split>.json` (P7bis: FHIR Bundle, "
        "API, queue, worker, model view with minimum-necessary pages and redacted identifiers, verifier, engine). "
        "Same model (claude-haiku-5-5) and prompt (agent@v2), real responses replayed from `eval/cassettes/`. "
        "Rates are k/n = value [95 % Wilson interval]. Synthetic data only. Never edited by hand.",
        "",
        "Nothing was tuned after looking at test or robust; the page rule was written from dev headings "
        "(see `results/minimum_necessary.json`).",
        "",
    ]
    rows: list[tuple[str, str]] = [
        ("Criterion accuracy", "criterion_accuracy"),
        ("Dangerous approvals (expected PEND, approved)", "dangerous_approval_rate"),
        ("Unjustified PEND (expected APPROVE, pended)", "unjustified_pend_rate"),
        ("Decision accuracy", "decision_accuracy"),
        ("Valid citations", "evidence_validity"),
        ("Injections detected", "injection_detection"),
    ]
    by_id: dict[str, dict[str, tuple[dict[str, Any], dict[str, Any]]]] = {}
    for split in SPLITS:
        base = load(f"{BASELINE}_{split}.json")["metrics"]
        pipe_file = load(f"pipeline_{split}.json")
        pipe = pipe_file["metrics"]
        pages = sum(len(case.pages) for case, _ in load_split(data, split))
        sent = pipe_file["pipeline"]
        lines += [
            f"## {split} ({base['n_cases']} cases)",
            "",
            "| Metric | Whole record (agent_v2_haiku) | API pipeline (agent_v2_haiku_pipeline) |",
            "|---|---|---|",
        ]
        lines += [f"| {label} | {rate(base[key])} | {rate(pipe[key])} |" for label, key in rows]
        lines += [
            f"| System errors | {base['system_errors']} | {pipe['system_errors']} |",
            f"| Pages sent to the model | {pages}/{pages} (100 %) | {sent['pages_sent']}/{sent['pages']} "
            f"({100 * sent['share_of_pages_sent']:.1f} %) |",
            f"| Cost, total (USD) | {base['usage']['total_cost_usd']:.6f} | {pipe['usage']['total_cost_usd']:.6f} |",
            f"| Cost per case, mean (USD) | {base['usage']['cost_usd_per_case']['mean']:.6f} | "
            f"{pipe['usage']['cost_usd_per_case']['mean']:.6f} |",
            "",
        ]
        for cid, r in base["criterion_accuracy_by_id"].items():
            by_id.setdefault(cid, {})[split] = (r, pipe["criterion_accuracy_by_id"][cid])
    lines += [
        "## Criterion accuracy by criterion (whole record -> API pipeline)",
        "",
        "| Criterion | " + " | ".join(SPLITS) + " |",
        "|---|" + "---|" * len(SPLITS),
    ]
    for cid in sorted(by_id):
        cells = []
        for split in SPLITS:
            b, p = by_id[cid][split]
            cells.append(f"{b['k']}/{b['n']} -> {p['k']}/{p['n']}" if b["n"] else "n/a")
        lines.append(f"| {cid} | " + " | ".join(cells) + " |")
    return "\n".join(lines) + "\n"


def main() -> int:
    OUTPUT.write_text(render(), encoding="utf-8")
    print(f"wrote {OUTPUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
