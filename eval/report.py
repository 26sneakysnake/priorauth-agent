"""Comparison table of every committed result, generated from results/*.json (never written by hand).

python -m eval.report            # writes results/comparison.md
python -m eval.report --check    # exit 1 if results/comparison.md is not up to date
"""

import argparse
import json
import sys
from pathlib import Path
from typing import Any

RESULTS = Path("results")
OUTPUT = RESULTS / "comparison.md"

MAIN = (
    ("rules_baseline", "Baseline 1: rules, no LLM"),
    ("llm_single_haiku", "Baseline 2: one Haiku call"),
    ("agent_v1_haiku", "Agent v1 (Haiku)"),
    ("agent_v2_haiku", "Agent v2 (Haiku)"),
    ("agent_v2_sonnet", "Agent v2 (Sonnet)"),
)
PROBES = (
    ("agent_lenient_haiku", "Probe: lenient prompt (Haiku)"),
    ("agent_degraded_haiku", "Gate fixture: degraded prompt (Haiku)"),
)
SPLITS = ("dev", "test", "robust")


def _rate(r: dict[str, Any]) -> str:
    if r["n"] == 0:
        return "n/a"
    lo, hi = r["ci95"]
    return f"{r['k']}/{r['n']} ({100 * r['value']:.1f} %, {100 * lo:.1f}-{100 * hi:.1f})"


def _ms(value: float | None) -> str:
    return "n/a" if value is None else f"{value / 1000:.1f} s"


def row(label: str, split: str, doc: dict[str, Any]) -> str:
    m = doc["metrics"]
    u = m["usage"]
    cost = u["total_cost_usd"]
    per_case = u["cost_usd_per_case"]["mean"] or 0.0
    lat = u["latency_ms_per_case"]
    cells = [
        label,
        split,
        _rate(m["dangerous_approval_rate"]),
        _rate(m["unjustified_pend_rate"]),
        _rate(m["criterion_accuracy"]),
        _rate(m["evidence_validity"]),
        _rate(m["decision_accuracy"]),
        f"{cost:.4f} ({per_case:.5f}/case)",
        f"{_ms(lat['p50'])} / {_ms(lat['p95'])}",
    ]
    return "| " + " | ".join(cells) + " |"


HEADER = (
    "| system | split | dangerous approvals | unjustified PEND | criterion accuracy | evidence valid before "
    "verification | decision accuracy | cost USD | latency p50 / p95 |\n|---|---|---|---|---|---|---|---|---|"
)


def render(results: Path = RESULTS) -> str:
    def table(systems: tuple[tuple[str, str], ...]) -> list[str]:
        lines = [HEADER]
        for system, label in systems:
            for split in SPLITS:
                path = results / f"{system}_{split}.json"
                if path.exists():
                    lines.append(row(label, split, json.loads(path.read_bytes())))
        return lines

    parts = [
        "# Comparison of all evaluated systems",
        "",
        "Generated by `python -m eval.report` from `results/<system>_<split>.json`; do not edit. Rates are k/n "
        "with the 95 % Wilson interval in percent. Cost and latency of LLM systems are those recorded in the "
        "cassettes (latency: sum of model calls per case). Splits: dev 100 cases (prompts iterated here), test 60 "
        "(frozen, run once per system), robust 40 (new templates, frozen, run once per system).",
        "",
        *table(MAIN),
        "",
        "Probes, dev only (not candidates for production):",
        "",
        *table(PROBES),
        "",
    ]
    return "\n".join(parts)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    text = render()
    if args.check:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != text:
            print(f"{OUTPUT} is out of date; run python -m eval.report", file=sys.stderr)
            return 1
        return 0
    OUTPUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUTPUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
